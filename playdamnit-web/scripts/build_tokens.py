#!/usr/bin/env python3
"""Generate dist/tokens.css from the website's globals.css.

Usage: build_tokens.py <path to apps/web/src/globals.css>
"""
import pathlib
import re
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "dist" / "tokens.css"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = pathlib.Path(sys.argv[1]).read_text()
    root = re.search(r":root\s*\{(.*?)\n\}", source, re.S).group(1)
    tokens = re.findall(r"^\s*(--[\w-]+):\s*([^;]+);", root, re.M)
    body = "\n".join(f"  {name}: {value.strip()};" for name, value in tokens)
    OUT.write_text(
        "/* Generated by scripts/build_tokens.py from apps/web/src/globals.css. Do not edit. */\n"
        f":root {{\n{body}\n}}\n"
    )
    print(f"wrote {OUT} ({len(tokens)} tokens)")


if __name__ == "__main__":
    main()
