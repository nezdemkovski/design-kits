#!/usr/bin/env python3
"""Generate dist/tokens.css from the app's color asset catalog.

Usage: build_tokens.py <path to Assets.xcassets/Colors>
"""
import json
import pathlib
import re
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "dist" / "tokens.css"


def kebab(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def css(components):
    def channel(v):
        v = v.strip()
        if v.startswith("0x"):
            return int(v, 16)
        f = float(v)
        return round(f * 255) if f <= 1 else int(f)

    r, g, b = (channel(components[k]) for k in ("red", "green", "blue"))
    a = float(components.get("alpha", "1"))
    if a >= 1:
        return f"#{r:02X}{g:02X}{b:02X}"
    return f"rgb({r} {g} {b} / {round(a * 100)}%)"


def load(colors_dir):
    light, dark = {}, {}
    for colorset in sorted(colors_dir.rglob("*.colorset")):
        name = "--pd-" + kebab(colorset.stem)
        for entry in json.loads((colorset / "Contents.json").read_text())["colors"]:
            value = css(entry["color"]["components"])
            appearances = {a.get("value") for a in entry.get("appearances", [])}
            (dark if "dark" in appearances else light)[name] = value
    return light, dark


def block(selector, values):
    lines = "\n".join(f"  {k}: {v};" for k, v in values.items())
    return f"{selector} {{\n{lines}\n}}\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    light, dark = load(pathlib.Path(sys.argv[1]))
    dark = {k: v for k, v in dark.items() if light.get(k) != v}
    OUT.write_text(
        "/* Generated by scripts/build_tokens.py from the app's Assets.xcassets. Do not edit. */\n"
        + block(":root", light)
        + "\n"
        + block(':root[data-theme="dark"]', dark)
        + "\n@media (prefers-color-scheme: dark) {\n"
        + block('  :root[data-theme="auto"]', dark).replace("\n  --", "\n    --").replace("\n}", "\n  }")
        + "}\n"
    )
    print(f"wrote {OUT} ({len(light)} tokens, {len(dark)} dark overrides)")


if __name__ == "__main__":
    main()
